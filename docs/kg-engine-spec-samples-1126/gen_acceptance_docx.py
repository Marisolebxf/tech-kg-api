    para(doc, title, east="黑体", size=24, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, after=14)
    para(doc, sub, east="楷体", size=12, align=WD_ALIGN_PARAGRAPH.CENTER, after=40)
    para(doc, f"文档编号：{doc_no}", east="宋体", size=13, align=WD_ALIGN_PARAGRAPH.CENTER, after=4)
    para(doc, "版    本：V0.1（样例稿，供评审）", east="宋体", size=13, align=WD_ALIGN_PARAGRAPH.CENTER, after=4)
