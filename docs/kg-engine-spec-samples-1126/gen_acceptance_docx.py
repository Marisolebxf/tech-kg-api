def set_run(r, east="宋体", size=12, bold=False, ascii_font="Times New Roman"):
    r.font.name = ascii_font
    r.font.size = Pt(size)
    r.font.bold = bold
    r._element.rPr.rFonts.set(qn("w:eastAsia"), east)

def para(doc, text, east="宋体", size=12, bold=False, align=None, before=0, after=4, pb=False, indent=None):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_run(r, east, size, bold)
    pf = p.paragraph_format
    pf.space_before, pf.space_after, pf.line_spacing = Pt(before), Pt(after), 1.35
    pf.page_break_before = pb
    if indent is not None:
        pf.left_indent = Cm(indent)
    if align is not None:
        p.alignment = align
    return p

def add_table(doc, caption, headers, rows):
    if caption:
        para(doc, caption, east="黑体", size=10.5, bold=True, before=6, after=2)
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.autofit = True
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ""
        r = c.paragraphs[0].add_run(h)
        set_run(r, "黑体", 10.5, True)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run(str(v))
            set_run(r, "宋体", 10.5)

